package platform

import "time"

// IdempotencyKeyTTL 是一个幂等键的保留窗口。
//
// 【为什么放在 platform，而不是各自包一份】两条端点（发消息、跑 Agent）
// 都带幂等键，语义是同一件事：「这个键在多长时间内有效」。各写一个
// `24 * time.Hour` 的话，将来改一个忘一个，而两边都叫幂等——漂移不会被
// 任何编译错误或测试发现。这是 ADR-008 定的，改它要连那篇一起改。
//
// 【为什么是 24 小时】键的用途是覆盖一次客户端重试（秒到分钟级）。
// Agent run 比消息贵，但「贵的操作更需要自动去重」不等于「窗口要更长」：
// 隔了一天之后用户再点一次「运行」，本来就应该真的跑一次。
//
// 【过期之后同一个键再来 = 重新执行，不是报错】键过期后行已经被清掉，
// 服务端没有任何记录能证明这个键出现过。这时唯一自洽的行为是把它当成
// 一次全新的请求；报错会让「昨天点过、今天再点」变成一个用户无法理解、
// 也无法绕过的失败。
const IdempotencyKeyTTL = 24 * time.Hour
